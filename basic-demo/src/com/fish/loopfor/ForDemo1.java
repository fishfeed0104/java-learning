package com.fish.loopfor;

public class ForDemo1 {
    public static void main(String[] args) {
        /*
            实现游戏中连续跳跃十次，用输出语句模拟跳跃的逻辑

            格式：
            for(初始化语句;条件判断语句;条件控制语句){
                循环语句);
            }
         */

        for (int i = 1; i <= 10; i++) {
            System.out.println("跳跃" + (i) + "次");
        }
    }
}
